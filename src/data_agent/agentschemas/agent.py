"""
Schema definitions for the SQL Analyst Agent.
"""

from typing import Literal

from pydantic import Field

from data_agent.agentschemas.workflow import WorkflowOutput


class AgentSchema(WorkflowOutput):
    messages: list = Field(..., description="Conversation snapshot for the SQL workflow")
    schema_context: str = ""
    question_status: Literal["pending", "clear", "ambiguous", "unsupported", "error"] = "pending"
    question_feedback: str = ""
    user_question: str = Field(..., description="The question asked by the user")
    curated_question: str = Field(default="", description="Crated questions for the agent")
    prompt_query_context: str = Field(
        default="", description="A detailed Prompt query context with SQL DB for the agent"
    )
    is_safe: Literal["Yes", "No"] = Field(
        default="No", description="Indicates if the content is safe for the agent"
    )
    comments: str = Field(
        default="", description="comments regarding the safety evaluation of the SQL query"
    )
    generated_sql_query: str = Field(default="", description="The SQL query generated by the agent")
    sql_query_execution_result: str = Field(
        default="", description="The result of executing the SQL query"
    )
